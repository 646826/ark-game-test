const TABLES: Record<SupportedLanguage, TranslationTable> = { en: EN, es: ES, fr: FR, de: DE, it: IT };

export class I18n {
  #language: SupportedLanguage;

  public constructor(language: SupportedLanguage) {
    this.#language = language;
  }

  public get language(): SupportedLanguage {
    return this.#language;
  }

  public set language(language: SupportedLanguage) {
    this.#language = language;
    document.documentElement.lang = language;
  }

  public t(key: TranslationKey, params: Record<string, string | number> = {}): string {
    const template = TABLES[this.#language][key] ?? EN[key];
    return Object.entries(params).reduce(
      (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
      template,
    );
  }

  public formatNumber(value: number): string {
    return new Intl.NumberFormat(this.#language).format(value);
  }

  public formatTime(milliseconds: number): string {
    const totalSeconds = Math.max(0, Math.floor(milliseconds / 1000));
    const minutes = Math.floor(totalSeconds / 60);
    const seconds = totalSeconds % 60;
    return `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
  }
}

export function detectLanguage(): SupportedLanguage {
  const requested = new URLSearchParams(location.search).get('lang')?.toLowerCase().split('-')[0];
  const browser = navigator.language.toLowerCase().split('-')[0];
  const candidate = requested ?? browser;
  return candidate === 'es' || candidate === 'fr' || candidate === 'de' || candidate === 'it' ? candidate : 'en';
}

export function isSupportedLanguage(value: string): value is SupportedLanguage {
  return value === 'en' || value === 'es' || value === 'fr' || value === 'de' || value === 'it';
}

